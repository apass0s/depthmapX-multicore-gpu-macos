// depthmapX GPU module (Metal) - the device layer on Metal (macOS)
//
// Compiled with ARC. The kernels (dmx_metal_shared.h + dmx_metal_kernels.metal) are
// embedded at build time and compiled when the module is first used, so building needs
// only the Command Line Tools (the offline `metal` compiler comes with full Xcode).
// Buffers use shared storage: on Apple GPUs that is the unified memory itself; on Intel
// Macs with a discrete GPU it is system memory the GPU reads over PCIe (correct, slower).

#import <Foundation/Foundation.h>
#import <Metal/Metal.h>

#include "dmx_metal_backend.h"

#include <cstdio>
#include <vector>

namespace dmxmetal {

struct Buffer {
    id<MTLBuffer> buffer = nil;
};

namespace {

// static const char kKernelSource[], generated by gpu/CMakeLists.txt
#include "dmx_metal_source.inc"

const char *const kKernelNames[kKernelCount] = {"dmx_probe",
                                                "dmx_vis_local_rows",
                                                "dmx_vis_global_pull",
                                                "dmx_vis_global_downsweep",
                                                "dmx_vis_global_combine",
                                                "dmx_vis_global_count"};

std::string message(NSError *error) {
    if (!error) {
        return "unknown error";
    }
    const char *text = error.localizedDescription.UTF8String;
    return text ? std::string(text) : std::string("unknown error");
}

class MetalDevice : public Device {
  public:
    bool init(int *code, std::string &error) {
        @autoreleasepool {
            m_device = MTLCreateSystemDefaultDevice();
            if (!m_device) {
                *code = DMX_GPU_ERR_NO_DEVICE;
                error = "no Metal device";
                return false;
            }
            m_queue = [m_device newCommandQueue];
            MTLCompileOptions *options = [MTLCompileOptions new];
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wdeprecated-declarations"
            options.fastMathEnabled = NO; // the kernels are integer-only; kept strict anyway
#pragma clang diagnostic pop
            NSError *err = nil;
            NSString *source = [NSString stringWithUTF8String:kKernelSource];
            id<MTLLibrary> library = [m_device newLibraryWithSource:source options:options error:&err];
            if (!library) {
                *code = DMX_GPU_ERR_UNSUPPORTED;
                error = "the Metal kernels failed to compile: " + message(err);
                return false;
            }
            for (int i = 0; i < kKernelCount; ++i) {
                id<MTLFunction> function =
                    [library newFunctionWithName:[NSString stringWithUTF8String:kKernelNames[i]]];
                if (!function) {
                    *code = DMX_GPU_ERR_UNSUPPORTED;
                    error = std::string("Metal kernel missing: ") + kKernelNames[i];
                    return false;
                }
                m_pipelines[i] = [m_device newComputePipelineStateWithFunction:function error:&err];
                if (!m_pipelines[i]) {
                    *code = DMX_GPU_ERR_UNSUPPORTED;
                    error = std::string("Metal pipeline ") + kKernelNames[i] + ": " + message(err);
                    return false;
                }
            }
        }
        *code = DMX_GPU_OK;
        return true;
    }

    void describe(dmx_gpu_device_info &info) const override {
        @autoreleasepool {
            std::snprintf(info.name, sizeof(info.name), "%s", m_device.name.UTF8String);
            // Newest Apple GPU family (MTLGPUFamilyApple1 = 1001 ... Apple9 = 1009); 0 when the
            // GPU is a Mac-family one (Intel Macs), with cc_minor 2 for MTLGPUFamilyMac2 (2002).
            info.cc_major = 0;
            info.cc_minor = 0;
            for (int family = 9; family >= 1; --family) {
                if ([m_device supportsFamily:(MTLGPUFamily)(1000 + family)]) {
                    info.cc_major = family;
                    break;
                }
            }
            if (info.cc_major == 0 && [m_device supportsFamily:(MTLGPUFamily)2002]) {
                info.cc_minor = 2;
            }
            info.total_mem = m_device.recommendedMaxWorkingSetSize;
            const uint64_t used = m_device.currentAllocatedSize;
            info.free_mem = info.total_mem > used ? info.total_mem - used : 0;
        }
    }
    uint64_t workingSetBytes() const override { return m_device.recommendedMaxWorkingSetSize; }
    uint64_t allocatedBytes() const override { return m_device.currentAllocatedSize; }
    uint64_t maxBufferBytes() const override { return m_device.maxBufferLength; }
    uint32_t maxThreadgroupMemory() const override { return uint32_t(m_device.maxThreadgroupMemoryLength); }
    uint32_t maxThreadsPerThreadgroup(Kernel kernel) const override {
        return uint32_t(m_pipelines[int(kernel)].maxTotalThreadsPerThreadgroup);
    }

    Buffer *allocate(size_t bytes, std::string &error) override {
        @autoreleasepool {
            id<MTLBuffer> b = [m_device newBufferWithLength:bytes options:MTLResourceStorageModeShared];
            if (!b) {
                error = "cannot allocate a Metal buffer of " + std::to_string(bytes) + " bytes";
                return nullptr;
            }
            auto *out = new Buffer();
            out->buffer = b;
            return out;
        }
    }
    void release(Buffer *buffer) override { delete buffer; } // ARC releases the MTLBuffer
    void *contents(Buffer *buffer) override { return buffer->buffer.contents; }

    bool begin(std::string &error) override {
        @autoreleasepool {
            m_commands = [m_queue commandBuffer];
            m_encoder = m_commands ? [m_commands computeCommandEncoder] : nil; // serial dispatch
            if (!m_encoder) {
                m_commands = nil;
                error = "cannot create a Metal command buffer";
                return false;
            }
            return true;
        }
    }
    void setBuffer(Buffer *buffer, size_t offset, int index) override {
        [m_encoder setBuffer:buffer->buffer offset:offset atIndex:NSUInteger(index)];
    }
    void setBytes(const void *bytes, size_t length, int index) override {
        [m_encoder setBytes:bytes length:length atIndex:NSUInteger(index)];
    }
    void setThreadgroupMemory(size_t length, int index) override {
        [m_encoder setThreadgroupMemoryLength:length atIndex:NSUInteger(index)];
    }
    void dispatch(Kernel kernel, uint32_t groupsX, uint32_t groupsY, uint32_t threadsPerGroup) override {
        [m_encoder setComputePipelineState:m_pipelines[int(kernel)]];
        [m_encoder dispatchThreadgroups:MTLSizeMake(groupsX, groupsY, 1)
                  threadsPerThreadgroup:MTLSizeMake(threadsPerGroup, 1, 1)];
    }
    bool commit(bool wait, std::string &error) override {
        @autoreleasepool {
            [m_encoder endEncoding];
            [m_commands commit];
            m_pending.push_back(m_commands);
            m_encoder = nil;
            m_commands = nil;
        }
        return wait ? waitAll(error) : true;
    }
    bool waitAll(std::string &error) override {
        bool ok = true;
        @autoreleasepool {
            for (id<MTLCommandBuffer> commands : m_pending) {
                [commands waitUntilCompleted];
                if (commands.status == MTLCommandBufferStatusError && ok) {
                    ok = false;
                    error = "Metal command buffer failed: " + message(commands.error);
                }
            }
            m_pending.clear();
        }
        return ok;
    }

  private:
    id<MTLDevice> m_device = nil;
    id<MTLCommandQueue> m_queue = nil;
    id<MTLComputePipelineState> m_pipelines[kKernelCount];
    id<MTLCommandBuffer> m_commands = nil;
    id<MTLComputeCommandEncoder> m_encoder = nil;
    std::vector<id<MTLCommandBuffer>> m_pending;
};

} // namespace

std::unique_ptr<Device> createDevice(int *code, std::string &error) {
    std::unique_ptr<MetalDevice> device(new MetalDevice());
    if (!device->init(code, error)) {
        return nullptr;
    }
    return device;
}

} // namespace dmxmetal
